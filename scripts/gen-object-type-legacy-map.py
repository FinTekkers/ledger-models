#!/usr/bin/env python3
"""Writes the legacy object_class -> ObjectTypeProto map for JS and Rust (LM-297).

google-protobuf (JS) and prost (Rust) cannot read the `(legacy_object_class)`
enum-value options at runtime, so their helpers load this generated mirror.
The source of truth is ledger-models-protos/fintekkers/models/util/object_type.proto,
read here through the generated Python descriptor. Never edit the mirrors by hand.

Run from the repo root with the Python bindings importable:
    PYTHONPATH=ledger-models-python python3 scripts/gen-object-type-legacy-map.py [--check]
--check fails, writing nothing, if a mirror differs from what would be generated.
"""
import json
import sys
from pathlib import Path

from fintekkers.models.util import object_type_pb2
from fintekkers.models.util.object_type_pb2 import ObjectTypeProto

REPO_ROOT = Path(__file__).resolve().parents[1]
MIRRORS = [
    REPO_ROOT / "ledger-models-javascript" / "node" / "wrappers" / "util" / "object-type-legacy.json",
    REPO_ROOT / "ledger-models-rust" / "fintekkers" / "wrappers" / "util" / "object_type_legacy.json",
]


def render() -> str:
    legacy = {}
    for value in ObjectTypeProto.DESCRIPTOR.values:
        for name in value.GetOptions().Extensions[object_type_pb2.legacy_object_class]:
            legacy[name] = value.name
    return json.dumps({
        "_comment": "Generated by scripts/gen-object-type-legacy-map.py from the (legacy_object_class) "
                    "options in fintekkers/models/util/object_type.proto. Do not edit.",
        "legacy_object_class": dict(sorted(legacy.items())),
    }, indent=2) + "\n"


def main(argv) -> int:
    expected = render()
    if "--check" in argv:
        stale = [p for p in MIRRORS if not p.exists() or p.read_text() != expected]
        for p in stale:
            print(f"{p.relative_to(REPO_ROOT)} is stale: run scripts/gen-object-type-legacy-map.py", file=sys.stderr)
        return 1 if stale else 0
    for p in MIRRORS:
        p.write_text(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

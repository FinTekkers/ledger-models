//! Compact object type and version (LM-297), stage 1: write both forms, read the new one.
//!
//! Every message with `string object_class = 1` and `string version = 2` also
//! carries `ObjectTypeProto object_type = 1001` and `uint32 version_major /
//! version_minor / version_patch = 1002-1004`. Writers call [`stamp`] or
//! [`stamp_str`], which set the strings and the new fields. Readers call
//! [`read_type`] / [`read_version`] (or [`upgrade`]), which use the new fields
//! and fall back to the deprecated strings, logging one `log::warn!` per
//! distinct pair of strings. A fallback never panics: an unknown object_class
//! gives `ObjectTypeUnknown` and a malformed version gives 0.0.0. Empty strings
//! are the proto3 default and fall back silently.
//!
//! prost cannot read the `(legacy_object_class)` options at runtime, so the
//! string map comes from object_type_legacy.json, generated by
//! scripts/gen-object-type-legacy-map.py. See docs/adr/compact_object_type_and_version.md.
#![allow(deprecated)]


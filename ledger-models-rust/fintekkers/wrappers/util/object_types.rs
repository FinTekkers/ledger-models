    fn base64(text: &str) -> Vec<u8> {
        const ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        let mut out = Vec::new();
        let (mut acc, mut bits) = (0u32, 0);
        for c in text.bytes().filter(|&c| c != b'=') {
            let v = ALPHABET.iter().position(|&a| a == c).expect("base64") as u32;
            acc = (acc << 6) | v;
            bits += 6;
            if bits >= 8 {
                bits -= 8;
                out.push((acc >> bits) as u8);
            }
        }
        out
    }

    /// Field numbers present at the top level of an encoded message.
    fn top_level_field_numbers(data: &[u8]) -> Vec<u64> {
        let mut numbers = vec![];
        let mut i = 0;
        let varint = |i: &mut usize| -> u64 {
            let (mut result, mut shift) = (0u64, 0);
            loop {
                let b = data[*i];
                *i += 1;
                result |= ((b & 0x7f) as u64) << shift;
                shift += 7;
                if b & 0x80 == 0 {
                    return result;
                }
            }
        };
        while i < data.len() {
            let key = varint(&mut i);
            numbers.push(key >> 3);
            match key & 7 {
                0 => {
                    varint(&mut i);
                }
                1 => i += 8,
                2 => {
                    let len = varint(&mut i) as usize;
                    i += len;
                }
                5 => i += 4,
                other => panic!("unexpected wire type {other}"),
            }
        }
        numbers
    }

    fn check_case<M: ObjectTyped + Message + Default>(c: &Case) {
        let _g = guard();
        let expected_type = ObjectTypeProto::from_str_name(&c.expect.object_type).unwrap();
        let expected_version = (c.expect.version[0], c.expect.version[1], c.expect.version[2]);

        let message = M::decode(base64(&c.bytes).as_slice()).unwrap();
        assert_eq!(read_type(&message), expected_type, "{}", c.name);
        assert_eq!(read_version(&message), expected_version, "{}", c.name);
        assert_eq!(fallback_warnings(&c.object_class), usize::from(c.expect.warns), "{}", c.name);

        let data = upgrade(message).encode_to_vec();
        let present = top_level_field_numbers(&data);
        let compact = [
            (1001, expected_type as u32),
            (1002, expected_version.0),
            (1003, expected_version.1),
            (1004, expected_version.2),
        ];
        for (number, value) in compact {
            assert_eq!(present.contains(&number), value != 0, "{}: field {number}", c.name);
        }
        let reread = M::decode(data.as_slice()).unwrap();
        assert_eq!(reread.compact_type(), expected_type as i32, "{}", c.name);
        assert_eq!(reread.compact_version(), expected_version, "{}", c.name);
        assert_eq!(
            (reread.legacy_object_class(), reread.legacy_version()),
            (c.object_class.as_str(), c.version.as_str()),
            "{}",
            c.name
        );
    }


#[derive(serde::Deserialize)]
struct LegacyMirror {
    legacy_object_class: HashMap<String, String>,
}

fn legacy_map() -> &'static HashMap<String, ObjectTypeProto> {
    static LEGACY: OnceLock<HashMap<String, ObjectTypeProto>> = OnceLock::new();
    LEGACY.get_or_init(|| {
        let mirror: LegacyMirror = serde_json::from_str(include_str!("object_type_legacy.json"))
            .expect("object_type_legacy.json is valid: regenerate it");
        mirror
            .legacy_object_class
            .into_iter()
            .map(|(legacy, name)| {
                let value = ObjectTypeProto::from_str_name(&name).unwrap_or_else(|| {
                    panic!("object_type_legacy.json names {name}, which ObjectTypeProto lacks: regenerate it")
                });
                (legacy, value)
            })
            .collect()
    })
}

fn warned() -> &'static Mutex<HashSet<(String, String)>> {
    static WARNED: OnceLock<Mutex<HashSet<(String, String)>>> = OnceLock::new();
    WARNED.get_or_init(Default::default)
}

/// The ObjectTypeProto value an object_class string stands for, or `ObjectTypeUnknown`.
pub fn from_legacy(object_class: &str) -> ObjectTypeProto {
    legacy_map().get(object_class).copied().unwrap_or(ObjectTypeProto::ObjectTypeUnknown)
}

/// "1.2.3" -> (1, 2, 3); None unless exactly three decimal uint32 parts.
pub fn parse_version(version: &str) -> Option<Version> {
    let parts: Vec<&str> = version.split('.').collect();
    if parts.len() != 3 || parts.iter().any(|p| p.is_empty() || !p.bytes().all(|b| b.is_ascii_digit())) {
        return None;
    }
    Some((parts[0].parse().ok()?, parts[1].parse().ok()?, parts[2].parse().ok()?))
}

/// Sets object_class / version and their compact form on `message`, from a known version.
pub fn stamp<M: ObjectTyped>(mut message: M, object_type: ObjectTypeProto, object_class: &str, version: Version) -> M {
    let (major, minor, patch) = version;
    message.set_legacy(object_class.to_string(), format!("{major}.{minor}.{patch}"));
    message.set_compact_type(object_type as i32);
    message.set_compact_version(version);
    message
}

/// Like [`stamp`] for a caller-supplied version string, which must be empty
/// or three uint32 parts; anything else is a `Validation` error on `version`.
pub fn stamp_str<M: ObjectTyped>(
    mut message: M,
    object_type: ObjectTypeProto,
    object_class: &str,
    version: &str,
) -> Result<M, Error> {
    let parts = if version.is_empty() { Some((0, 0, 0)) } else { parse_version(version) };
    let parts = parts.ok_or_else(|| {
        Error::Validation(vec![FieldViolationProto {
            field: "version".to_string(),
            object_id: None,
            message: format!("version must be MAJOR.MINOR.PATCH, got '{version}'"),
        }])
    })?;
    message.set_legacy(object_class.to_string(), version.to_string());
    message.set_compact_type(object_type as i32);
    message.set_compact_version(parts);
    Ok(message)
}

fn warn_once<M: ObjectTyped + ?Sized>(message: &M, problems: &str) {
    let key = (message.legacy_object_class().to_string(), message.legacy_version().to_string());
    if !warned().lock().unwrap_or_else(|e| e.into_inner()).insert(key) {
        return;
    }
    log::warn!(
        "{} read from deprecated strings object_class='{}' version='{}'{}; re-save it to write \
         object_type and version_major/minor/patch (LM-297)",
        message.message_name(),
        message.legacy_object_class(),
        message.legacy_version(),
        problems
    );
}

/// Decodes the new fields, falling back field by field to the strings.
/// Returns the raw object_type number and the version.
fn decode<M: ObjectTyped + ?Sized>(message: &M) -> (i32, Version) {
    let mut object_type = message.compact_type();
    let mut version = message.compact_version();
    let mut problems = String::new();
    let mut used_strings = false;

    if object_type == ObjectTypeProto::ObjectTypeUnknown as i32 && !message.legacy_object_class().is_empty() {
        used_strings = true;
        object_type = from_legacy(message.legacy_object_class()) as i32;
        if object_type == ObjectTypeProto::ObjectTypeUnknown as i32 {
            problems.push_str(" (unknown object_class, using OBJECT_TYPE_UNKNOWN)");
        }
    }
    if version == (0, 0, 0) && !message.legacy_version().is_empty() {
        used_strings = true;
        match parse_version(message.legacy_version()) {
            Some(parsed) => version = parsed,
            None => problems.push_str(" (malformed version, using 0.0.0)"),
        }
    }

    if used_strings {
        warn_once(message, &problems);
    }
    (object_type, version)
}

/// The message's ObjectTypeProto value: object_type, else the object_class
/// string. A number newer than this enum reads as `ObjectTypeUnknown`.
pub fn read_type<M: ObjectTyped + ?Sized>(message: &M) -> ObjectTypeProto {
    ObjectTypeProto::from_i32(decode(message).0).unwrap_or(ObjectTypeProto::ObjectTypeUnknown)
}

/// The message's (major, minor, patch): the compact fields, else the version string.
pub fn read_version<M: ObjectTyped + ?Sized>(message: &M) -> Version {
    decode(message).1
}

/// The by-id lookup request the link resolvers send to the security service.
pub(crate) fn query_security_request(
    uu_ids: Vec<UuidProto>,
    as_of: Option<LocalTimestampProto>,
) -> QuerySecurityRequestProto {
    let request = QuerySecurityRequestProto { uu_ids, as_of, ..Default::default() };
    stamp(request, ObjectTypeProto::ObjectTypeQuerySecurityRequest, "SecurityRequest", (0, 0, 1))
}


/// (major, minor, patch).
pub type Version = (u32, u32, u32);

/// A generated message that carries object_class / version and their compact form.
pub trait ObjectTyped {
    fn message_name(&self) -> &'static str;
    fn legacy_object_class(&self) -> &str;
    fn legacy_version(&self) -> &str;
    fn set_legacy(&mut self, object_class: String, version: String);
    /// The raw `object_type` number, which may be newer than this enum.
    fn compact_type(&self) -> i32;
    fn compact_version(&self) -> Version;
    fn set_compact_type(&mut self, object_type: i32);
    fn set_compact_version(&mut self, version: Version);
}

macro_rules! object_typed {
    ($($ty:path => $name:literal),* $(,)?) => {$(
        impl ObjectTyped for $ty {
            fn message_name(&self) -> &'static str { $name }
            fn legacy_object_class(&self) -> &str { &self.object_class }
            fn legacy_version(&self) -> &str { &self.version }
            fn set_legacy(&mut self, object_class: String, version: String) {
                self.object_class = object_class;
                self.version = version;
            }
            fn compact_type(&self) -> i32 { self.object_type }
            fn compact_version(&self) -> Version {
                (self.version_major, self.version_minor, self.version_patch)
            }
            fn set_compact_type(&mut self, object_type: i32) { self.object_type = object_type; }
            fn set_compact_version(&mut self, (major, minor, patch): Version) {
                self.version_major = major;
                self.version_minor = minor;
                self.version_patch = patch;
            }
        }
    )*};
}


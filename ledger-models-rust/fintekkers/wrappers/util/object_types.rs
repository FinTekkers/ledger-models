    impl log::Log for Capture {
        fn enabled(&self, _: &log::Metadata) -> bool {
            true
        }
        fn log(&self, record: &log::Record) {
            if record.level() == log::Level::Warn {
                captured().lock().unwrap().push(record.args().to_string());
            }
        }
        fn flush(&self) {}
    }

    /// Serialises the tests that count warnings: the warn-once set is process-wide.
    fn guard() -> std::sync::MutexGuard<'static, ()> {
        static LOGGER: Capture = Capture;
        static INIT: OnceLock<()> = OnceLock::new();
        static LOCK: Mutex<()> = Mutex::new(());
        INIT.get_or_init(|| {
            let _ = log::set_logger(&LOGGER);
            log::set_max_level(log::LevelFilter::Warn);
        });
        let guard = LOCK.lock().unwrap_or_else(|e| e.into_inner());
        reset_warnings_for_tests();
        captured().lock().unwrap().clear();
        guard
    }

    fn fallback_warnings(object_class: &str) -> usize {
        let needle = format!("object_class='{object_class}'");
        captured()
            .lock()
            .unwrap()
            .iter()
            .filter(|l| l.contains("(LM-297)") && l.contains(&needle))
            .count()
    }


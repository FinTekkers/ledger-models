/// Fills the compact fields from the strings where they are unset; returns `message`.
/// The strings are kept, so re-serialising writes both forms.
pub fn upgrade<M: ObjectTyped>(mut message: M) -> M {
    let (object_type, version) = decode(&message);
    message.set_compact_type(object_type);
    message.set_compact_version(version);
    message
}

/// Forgets which strings have warned. Tests only.
pub fn reset_warnings_for_tests() {
    warned().lock().unwrap_or_else(|e| e.into_inner()).clear();
}


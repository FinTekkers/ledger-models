//! Builders stamp what they build (LM-325, LM-322 Part D).
//!
//! Every public builder in `fintekkers/wrappers/**` that creates a message
//! is a `BUILDERS` row. Each row's output is encoded, decoded by reflection
//! and walked: the root and every nested message with an `object_type` field
//! must carry its own type and version (0, 0, 1). A caller's proto passed in
//! is left as given (LM-322's pass-through ruling).
//!
//! The completeness check parses the wrapper sources with `syn` (a
//! dev-dependency, so a consumer's build never compiles or runs it) and
//! finds every `pub fn` / `pub async fn` whose return type is a message or a
//! struct holding one. Each must be a `BUILDERS` or an `EXCLUDED` row.
//!
//! Scan limits: the scan reads source, not expanded code. It cannot see
//! functions generated by `macro_rules!`, return types hidden behind a type
//! alias, or generic returns such as `LinkCache::get -> Option<V>`. None of
//! these returns a library-built message today.
//!
//! Runs only with `cargo test --features test-utils`.


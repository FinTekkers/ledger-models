#[test]
fn syn_is_a_dev_dependency_and_there_is_no_build_script() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    assert!(!manifest.join("build.rs").exists(), "a build.rs would ship and run in consumers' builds");
    let toml = std::fs::read_to_string(manifest.join("Cargo.toml")).unwrap();
    let mut section = String::new();
    let mut in_dev = false;
    for line in toml.lines().map(str::trim) {
        if line.starts_with('[') {
            section = line.to_string();
            continue;
        }
        let key = line.split(['=', ' ']).next().unwrap_or("");
        if key != "syn" && !section.ends_with("dependencies.syn]") {
            continue;
        }
        if section.contains("dev-dependencies") {
            in_dev = true;
        } else if section.contains("dependencies") {
            panic!("syn is under {section}; it must stay a dev-dependency");
        }
    }
    assert!(in_dev, "syn is missing from [dev-dependencies]");
}

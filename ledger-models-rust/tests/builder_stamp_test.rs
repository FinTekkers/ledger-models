// ---------- the stamp walk ----------

fn pool() -> DescriptorPool {
    DescriptorPool::decode(LEDGER_MODELS_PROTO_FILE_DESCRIPTOR_SET).expect("descriptor set decodes")
}

/// Decodes `bytes` as `full_name` and checks the root and every nested
/// message (including list items) that has an own type. Ok holds the paths
/// checked (`$` is the root); Err holds one line per unstamped path.
fn check_stamps(full_name: &str, bytes: &[u8]) -> Result<Vec<String>, Vec<String>> {
    let desc = pool().get_message_by_name(full_name).unwrap_or_else(|| panic!("no message {full_name}"));
    let message = DynamicMessage::decode(desc, bytes).expect("message decodes");
    let (mut checked, mut errors) = (vec![], vec![]);
    walk(&message, "$".to_string(), &mut checked, &mut errors);
    if errors.is_empty() {
        Ok(checked)
    } else {
        Err(errors)
    }
}

fn walk(message: &DynamicMessage, path: String, checked: &mut Vec<String>, errors: &mut Vec<String>) {
    let name = message.descriptor().full_name().to_string();
    if let Some(own) = own_type_by_full_name(&name) {
        let object_type = match message.get_field_by_name("object_type").as_deref() {
            Some(Value::EnumNumber(n)) => *n,
            _ => 0,
        };
        let version = if message.has_field_by_name("version") {
            message.get_field_by_name("version").and_then(|v| v.as_message().map(version_of))
        } else {
            None
        };
        if object_type != own as i32 || version != Some(SCHEMA_VERSION) {
            errors.push(format!(
                "{path} ({name}): object_type {object_type}, version {version:?}; want {} and {SCHEMA_VERSION:?}",
                own as i32
            ));
        }
        checked.push(path.clone());
    }
    for (field, value) in message.fields() {
        let child = format!("{path}.{}", field.name());
        match value {
            Value::Message(m) => walk(m, child, checked, errors),
            Value::List(items) => {
                for (i, item) in items.iter().enumerate() {
                    if let Value::Message(m) = item {
                        walk(m, format!("{child}[{i}]"), checked, errors);
                    }
                }
            }
            _ => {}
        }
    }
}

fn version_of(v: &DynamicMessage) -> (u32, u32, u32) {
    let part = |n: &str| v.get_field_by_name(n).and_then(|x| x.as_u32()).unwrap_or(0);
    (part("major"), part("minor"), part("patch"))
}

// ---------- the completeness scan ----------

/// Rust type names of every message with an own type: the last segment of
/// each `object_typed!` row's proto full name, in prost's UpperCamelCase
/// (`API_Key` becomes `ApiKey`).
fn typed_names() -> BTreeSet<String> {
    own_type_stampers().into_iter().map(|(full_name, _)| rust_type_name(full_name)).collect()
}

fn rust_type_name(full_name: &str) -> String {
    let last = full_name.rsplit('.').next().unwrap();
    if !last.contains('_') {
        return last.to_string();
    }
    last.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let first = chars.next().unwrap().to_ascii_uppercase();
            first.to_string() + &chars.as_str().to_ascii_lowercase()
        })
        .collect()
}

/// `typed`, plus every struct (not a `*Builder`) in `srcs` with a field whose
/// type names a message type, repeated until nothing new is added.
fn message_types(srcs: &[(String, String)], typed: &BTreeSet<String>) -> BTreeSet<String> {
    let structs: Vec<(String, Vec<syn::Type>)> = srcs
        .iter()
        .flat_map(|(file, src)| {
            let ast = syn::parse_file(src).unwrap_or_else(|e| panic!("{file}: {e}"));
            let mut collector = StructCollector::default();
            collector.visit_file(&ast);
            collector.structs
        })
        .filter(|(name, _)| !name.ends_with("Builder"))
        .collect();
    let mut msgs = typed.clone();
    loop {
        let before = msgs.len();
        for (name, fields) in &structs {
            if !msgs.contains(name) && fields.iter().any(|ty| names_in(ty).iter().any(|n| msgs.contains(n))) {
                msgs.insert(name.clone());
            }
        }
        if msgs.len() == before {
            return msgs;
        }
    }
}

#[derive(Default)]
struct StructCollector {
    structs: Vec<(String, Vec<syn::Type>)>,
}

impl<'ast> Visit<'ast> for StructCollector {
    fn visit_item_mod(&mut self, m: &'ast syn::ItemMod) {
        if !is_cfg_test(&m.attrs) {
            syn::visit::visit_item_mod(self, m);
        }
    }

    fn visit_item_struct(&mut self, s: &'ast syn::ItemStruct) {
        let fields = s.fields.iter().map(|f| f.ty.clone()).collect();
        self.structs.push((s.ident.to_string(), fields));
    }
}

/// Every type name mentioned anywhere in `ty`, generics included.
fn names_in(ty: &syn::Type) -> Vec<String> {
    #[derive(Default)]
    struct Names(Vec<String>);
    impl<'ast> Visit<'ast> for Names {
        fn visit_path_segment(&mut self, seg: &'ast syn::PathSegment) {
            self.0.push(seg.ident.to_string());
            syn::visit::visit_path_segment(self, seg);
        }
    }
    let mut names = Names::default();
    names.visit_type(ty);
    names.0
}

fn is_cfg_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path().is_ident("cfg")
            && a.parse_args::<syn::Meta>().map_or(false, |m| m.path().is_ident("test"))
    })
}

/// True when `ty` returns an owned message: a name in `msgs`, possibly inside
/// Result, Option, Vec, Box or a tuple. `Self` is `self_ty`. A borrow is not
/// a created message.
fn returns_message(ty: &syn::Type, self_ty: Option<&str>, msgs: &BTreeSet<String>) -> bool {
    match ty {
        syn::Type::Path(p) => {
            let Some(seg) = p.path.segments.last() else { return false };
            let name = seg.ident.to_string();
            let name = if name == "Self" { self_ty.unwrap_or("Self").to_string() } else { name };
            if msgs.contains(&name) {
                return true;
            }
            if !matches!(name.as_str(), "Result" | "Option" | "Vec" | "Box") {
                return false;
            }
            match &seg.arguments {
                syn::PathArguments::AngleBracketed(args) => args.args.iter().any(|arg| {
                    matches!(arg, syn::GenericArgument::Type(t) if returns_message(t, self_ty, msgs))
                }),
                _ => false,
            }
        }
        syn::Type::Tuple(t) => t.elems.iter().any(|e| returns_message(e, self_ty, msgs)),
        syn::Type::Paren(p) => returns_message(&p.elem, self_ty, msgs),
        syn::Type::Group(g) => returns_message(&g.elem, self_ty, msgs),
        _ => false,
    }
}

struct BuilderFinder<'a> {
    file_stem: String,
    msgs: &'a BTreeSet<String>,
    found: Vec<String>,
}

impl BuilderFinder<'_> {
    fn check(&mut self, sig: &syn::Signature, self_ty: Option<&str>, name: String) {
        let syn::ReturnType::Type(_, ret) = &sig.output else { return };
        // A chained setter (`self` by value, returning Self) passes its
        // receiver along; it does not create a message.
        let by_value_self = matches!(sig.inputs.first(), Some(syn::FnArg::Receiver(r)) if r.reference.is_none());
        let returns_self = matches!(&**ret, syn::Type::Path(p)
            if p.path.segments.last().map_or(false, |s| s.ident == "Self" || Some(s.ident.to_string().as_str()) == self_ty));
        if by_value_self && returns_self {
            return;
        }
        if returns_message(ret, self_ty, self.msgs) {
            self.found.push(name);
        }
    }
}

impl<'ast> Visit<'ast> for BuilderFinder<'_> {
    fn visit_item_mod(&mut self, m: &'ast syn::ItemMod) {
        if !is_cfg_test(&m.attrs) {
            syn::visit::visit_item_mod(self, m);
        }
    }

    fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
        if matches!(f.vis, syn::Visibility::Public(_)) && !is_cfg_test(&f.attrs) {
            let name = format!("{}::{}", self.file_stem, f.sig.ident);
            self.check(&f.sig, None, name);
        }
    }

    fn visit_item_impl(&mut self, i: &'ast syn::ItemImpl) {
        // Trait methods are not part of the inherent public API scanned here.
        if i.trait_.is_some() || is_cfg_test(&i.attrs) {
            return;
        }
        let syn::Type::Path(p) = &*i.self_ty else { return };
        let Some(seg) = p.path.segments.last() else { return };
        let self_ty = seg.ident.to_string();
        for item in &i.items {
            if let syn::ImplItem::Fn(f) = item {
                if matches!(f.vis, syn::Visibility::Public(_)) && !is_cfg_test(&f.attrs) {
                    let name = format!("{self_ty}::{}", f.sig.ident);
                    self.check(&f.sig, Some(&self_ty), name);
                }
            }
        }
    }
}

/// Public builders in one source file, as `<Type>::<fn>` for methods and
/// `<file_stem>::<fn>` for free functions.
fn public_builders(file: &str, src: &str, msgs: &BTreeSet<String>) -> Vec<String> {
    let ast = syn::parse_file(src).unwrap_or_else(|e| panic!("{file}: {e}"));
    let file_stem = Path::new(file).file_stem().unwrap().to_string_lossy().to_string();
    let mut finder = BuilderFinder { file_stem, msgs, found: vec![] };
    finder.visit_file(&ast);
    finder.found
}

/// Every problem with the tables against what the scan `found`: an unlisted
/// builder, a stale listed or excluded name, or an exclusion with no reason.
fn completeness_report(found: &[String], listed: &[&str], excluded: &[(&str, &str)]) -> Vec<String> {
    let mut report = vec![];
    for name in found {
        if !listed.contains(&name.as_str()) && !excluded.iter().any(|(e, _)| e == name) {
            report.push(format!("unlisted builder: {name} (add it to BUILDERS, or to EXCLUDED with a reason)"));
        }
    }
    for name in listed {
        if !found.iter().any(|f| f == name) {
            report.push(format!("stale listed builder: {name}"));
        }
    }
    for (name, reason) in excluded {
        if !found.iter().any(|f| f == name) {
            report.push(format!("stale excluded builder: {name}"));
        }
        if reason.trim().is_empty() {
            report.push(format!("exclusion without a reason: {name}"));
        }
    }
    report
}

/// Every `.rs` file under `fintekkers/wrappers`, as (relative path, source).
fn wrapper_sources() -> Vec<(String, String)> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("fintekkers/wrappers");
    let mut srcs: Vec<(String, String)> = walkdir::WalkDir::new(&root)
        .into_iter()
        .map(|e| e.expect("walk wrappers"))
        .filter(|e| e.path().extension().map_or(false, |x| x == "rs"))
        .map(|e| {
            let rel = e.path().strip_prefix(&root).unwrap().to_string_lossy().to_string();
            (rel, std::fs::read_to_string(e.path()).expect("read source"))
        })
        .collect();
    srcs.sort();
    srcs
}

fn scan(srcs: &[(String, String)]) -> Vec<String> {
    let msgs = message_types(srcs, &typed_names());
    let mut found: Vec<String> = srcs.iter().flat_map(|(file, src)| public_builders(file, src, &msgs)).collect();
    found.sort();
    found
}

fn listed() -> Vec<&'static str> {
    BUILDERS.iter().map(|(name, ..)| *name).collect()
}


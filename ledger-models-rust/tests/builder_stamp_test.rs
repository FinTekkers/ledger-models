#[test]
fn every_listed_builder_stamps_itself_and_nested_messages() {
    let mut failures = vec![];
    for (name, full_name, call, must_check) in BUILDERS {
        match check_stamps(full_name, &call()) {
            Ok(checked) => {
                assert!(!checked.is_empty(), "{name}: the walk checked nothing");
                for path in *must_check {
                    assert!(checked.iter().any(|c| c == path), "{name}: the walk did not check {path}; checked {checked:?}");
                }
            }
            Err(errors) => failures.extend(errors.into_iter().map(|e| format!("{name}: {e}"))),
        }
    }
    assert!(failures.is_empty(), "unstamped messages:\n{}", failures.join("\n"));
}

#[test]
fn the_walk_reports_an_unstamped_nested_message_by_path() {
    let security = stamp_own(SecurityProto {
        settlement_currency: Some(Box::new(SecurityProto {
            non_bond_details: Some(NonBondDetails::CashDetails(CashDetailsProto { cash_id: "USD".to_string() })),
            ..Default::default()
        })),
        ..Default::default()
    });
    let errors = check_stamps(SECURITY, &security.encode_to_vec()).expect_err("the walk must fail");
    assert_eq!(errors.len(), 1, "{errors:?}");
    assert!(errors[0].starts_with("$.settlement_currency "), "{errors:?}");
}

#[test]
fn every_public_builder_is_listed_or_excluded() {
    let report = completeness_report(&scan(&wrapper_sources()), &listed(), EXCLUDED);
    assert!(report.is_empty(), "builder tables are out of date:\n{}", report.join("\n"));
}

#[test]
fn an_unlisted_builder_is_reported_by_name() {
    let fixture = r#"
        pub struct FixtureWrapper { proto: PriceProto }
        pub struct FixtureBuilder { proto: PriceProto }

        pub fn make_price() -> PriceProto { PriceProto::default() }
        pub fn make_wrapper() -> FixtureWrapper { FixtureWrapper { proto: PriceProto::default() } }
        pub(crate) fn decoy_price() -> PriceProto { PriceProto::default() }

        impl FixtureBuilder {
            pub fn price(self, p: i32) -> Self { self }
        }
    "#;
    let srcs = vec![("fixture.rs".to_string(), fixture.to_string())];
    let report = completeness_report(&scan(&srcs), &[], &[]);
    assert!(report.iter().any(|r| r.contains("fixture::make_price")), "{report:?}");
    assert!(report.iter().any(|r| r.contains("fixture::make_wrapper")), "{report:?}");
    assert!(!report.iter().any(|r| r.contains("decoy_price")), "{report:?}");
    assert_eq!(report.len(), 2, "{report:?}");
}


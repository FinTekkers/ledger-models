/**
 * LM-410: ProductInputs.forSecurity and ValuationRequests.typed. The shared
 * cases live in test-fixtures/product-inputs/, one file per case, generated by
 * ledger-models-python/test/requests/test_product_input_builders.py and read
 * by the Python, JS and Rust tests too. See docs/adr/product_input_builders.md.
 */
class ProductInputBuildersTest {

    private static final Path FIXTURES = Path.of("..", "test-fixtures", "product-inputs");
    private static final HexFormat HEX = HexFormat.of();
    private static final Set<String> UNIT_PRICED = Set.of("equity", "cash");

    // ---- Fixture loading

    static List<JsonObject> cases() throws IOException {
        List<JsonObject> out = new ArrayList<>();
        try (Stream<Path> files = Files.list(FIXTURES)) {
            for (Path p : files.filter(f -> f.toString().endsWith(".json")).sorted().collect(Collectors.toList())) {
                try (Reader r = Files.newBufferedReader(p, StandardCharsets.UTF_8)) {
                    JsonObject c = new Gson().fromJson(r, JsonObject.class);
                    String file = p.getFileName().toString();
                    c.addProperty("name", file.substring(0, file.length() - ".json".length()));
                    out.add(c);
                }
            }
        }
        return out;
    }

    static Stream<JsonObject> successCases() throws IOException {
        return cases().stream().filter(c -> c.has("arm"));
    }

    static Stream<JsonObject> errorCases() throws IOException {
        return cases().stream().filter(c -> c.has("error"));
    }

    private static JsonObject fixture(String name) throws IOException {
        return cases().stream().filter(c -> c.get("name").getAsString().equals(name)).findFirst().orElseThrow();
    }

    private static byte[] bytes(JsonObject o, String key) {
        return HEX.parseHex(o.get(key).getAsString());
    }

    private static SecurityProto security(JsonObject c) throws InvalidProtocolBufferException {
        return SecurityProto.parseFrom(bytes(c, "security_hex"));
    }

    private static PriceProto price(JsonObject c) throws InvalidProtocolBufferException {
        return PriceProto.parseFrom(bytes(c, "price_hex"));
    }

    private static MarketData marketData(JsonObject c) throws InvalidProtocolBufferException {
        MarketData.Builder b = MarketData.builder();
        if (!c.has("market_data")) return b.build();
        JsonObject md = c.getAsJsonObject("market_data");
        if (md.has("cpi_hex")) b.cpi(InflationIndexInput.parseFrom(bytes(md, "cpi_hex")));
        if (md.has("curve_hex")) b.curve(YieldCurveInput.parseFrom(bytes(md, "curve_hex")));
        if (md.has("fixings_hex")) {
            List<ReferenceRateFixingProto> fixings = new ArrayList<>();
            for (JsonElement h : md.getAsJsonArray("fixings_hex")) {
                fixings.add(ReferenceRateFixingProto.parseFrom(HEX.parseHex(h.getAsString())));
            }
            b.fixings(fixings);
        }
        return b.build();
    }

    private static ProductInput forSecurity(JsonObject c) throws InvalidProtocolBufferException {
        return ProductInputs.forSecurity(security(c), price(c), marketData(c));
    }

    private static LocalTimestampProto asof(JsonObject c) throws InvalidProtocolBufferException {
        return LocalTimestampProto.parseFrom(bytes(c.getAsJsonObject("typed"), "asof_hex"));
    }

    private static PositionProto position(JsonObject c) throws InvalidProtocolBufferException {
        return PositionProto.parseFrom(bytes(c.getAsJsonObject("typed"), "position_hex"));
    }

    private static List<MeasureProto> measures(JsonObject c) {
        List<MeasureProto> out = new ArrayList<>();
        for (JsonElement m : c.getAsJsonObject("typed").getAsJsonArray("measures")) out.add(MeasureProto.valueOf(m.getAsString()));
        return out;
    }

    private static void assertError(RuntimeException raised, JsonObject error) {
        assertEquals(error.get("type").getAsString(), raised.getClass().getSimpleName());
        if (raised instanceof MissingMarketDataError) {
            MissingMarketDataError m = (MissingMarketDataError) raised;
            assertEquals(error.get("arm").getAsString(), m.getArm());
            assertEquals(error.get("kind").getAsString(), m.getKind().name());
            assertEquals(error.get("field").getAsString(), m.getField());
            assertTrue(m.getMessage().contains(m.getArm()) && m.getMessage().contains(m.getKind().name()), m.getMessage());
        }
    }

    // ---- forSecurity

    @Test
    void fixturesCoverEveryArmInValuationArms() throws IOException {
        JsonObject root;
        try (InputStream in = ProductInputs.class.getResourceAsStream("/hierarchy.json");
             Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
            root = new Gson().fromJson(r, JsonObject.class);
        }
        Set<String> arms = new TreeSet<>();
        for (JsonElement e : root.getAsJsonObject("valuation_arms").getAsJsonArray("entries")) {
            arms.add(e.getAsJsonObject().get("arm").getAsString());
        }
        List<String> fixtureArms = successCases().map(c -> c.get("arm").getAsString()).collect(Collectors.toList());
        assertEquals(arms, new TreeSet<>(fixtureArms));
        assertEquals(arms.size(), fixtureArms.size(), "one success fixture per arm");
    }

    @ParameterizedTest
    @MethodSource("successCases")
    void forSecurityMatchesFixtureBytes(JsonObject c) throws IOException {
        assertEquals(c.get("expected_hex").getAsString(), HEX.formatHex(forSecurity(c).toByteArray()), c.get("name").getAsString());
    }

    /** R1: the arm is armFor's, and each field is the input it came from. */
    @ParameterizedTest
    @MethodSource("successCases")
    void forSecurityFields(JsonObject c) throws IOException {
        SecurityProto security = security(c);
        PriceProto price = price(c);
        MarketData md = marketData(c);
        ProductInput out = ProductInputs.forSecurity(security, price, md);
        FieldDescriptor armField = ProductInput.getDescriptor().findFieldByNumber(out.getInputCase().getNumber());
        String arm = armField.getName();
        assertEquals(ProductInputs.armFor(security), arm);
        assertEquals(c.get("arm").getAsString(), arm);

        Message body = (Message) out.getField(armField);
        Descriptor d = body.getDescriptorForType();
        assertEquals(security, body.getField(d.findFieldByName("security")));
        String priceField = UNIT_PRICED.contains(arm) ? "unit_price" : "clean_price";
        String otherField = UNIT_PRICED.contains(arm) ? "clean_price" : "unit_price";
        assertEquals(price.getPrice(), body.getField(d.findFieldByName(priceField)));
        assertEquals(null, d.findFieldByName(otherField));
        FieldDescriptor costBasis = d.findFieldByName("cost_basis");
        if (costBasis != null) assertFalse(body.hasField(costBasis), "cost_basis is never set");
        if (arm.equals("tips")) assertEquals(md.cpi().orElseThrow(), out.getTips().getCpi());
        if (arm.equals("frn")) {
            assertEquals(md.fixings(), out.getFrn().getFixingsList());
            assertEquals(md.curve().orElseThrow(), out.getFrn().getCurve());
        }
    }

    @ParameterizedTest
    @MethodSource("errorCases")
    void forSecurityThrowsFixtureError(JsonObject c) throws IOException {
        SecurityProto security = security(c);
        PriceProto price = price(c);
        MarketData md = marketData(c);
        RuntimeException raised = assertThrows(RuntimeException.class, () -> ProductInputs.forSecurity(security, price, md));
        assertError(raised, c.getAsJsonObject("error"));
    }

    @Test
    void forSecurityWithNullMarketDataThrowsMissingCpi() throws IOException {
        JsonObject c = fixture("tips");
        SecurityProto security = security(c);
        PriceProto price = price(c);
        MissingMarketDataError e = assertThrows(MissingMarketDataError.class, () -> ProductInputs.forSecurity(security, price, null));
        assertEquals("tips", e.getArm());
        assertEquals(MarketDataKind.CPI_U, e.getKind());
    }

    // ---- ValuationRequests.typed

    @ParameterizedTest
    @MethodSource("successCases")
    void typedMatchesFixtureAndSetsOnlyTypedFields(JsonObject c) throws IOException {
        ProductInput productInput = forSecurity(c);
        PositionProto position = position(c);
        ValuationRequestProto request = ValuationRequests.typed(asof(c), productInput, position, measures(c));
        assertEquals(c.getAsJsonObject("typed").get("expected_hex").getAsString(), HEX.formatHex(request.toByteArray()));
        assertTrue(request.hasPositionInput());
        assertEquals(position, request.getPositionInput());
        assertEquals(productInput, request.getProductInput());
    }

    @ParameterizedTest
    @MethodSource("errorCases")
    void typedThrowsFixtureError(JsonObject c) throws IOException {
        ProductInput productInput = ProductInput.parseFrom(bytes(c.getAsJsonObject("typed"), "product_input_hex"));
        LocalTimestampProto asof = asof(c);
        PositionProto position = position(c);
        List<MeasureProto> measures = measures(c);
        RuntimeException raised = assertThrows(RuntimeException.class,
                () -> ValuationRequests.typed(asof, productInput, position, measures));
        assertError(raised, c.getAsJsonObject("error"));
    }

    @Test
    void typedRequiresPosition() throws IOException {
        JsonObject c = fixture("bond");
        ProductInput productInput = forSecurity(c);
        LocalTimestampProto asof = asof(c);
        ModelValidationException e = assertThrows(ModelValidationException.class,
                () -> ValuationRequests.typed(asof, productInput, null, measures(c)));
        assertEquals("position_input", e.getField());
    }

    @Test
    void typedRejectsAnArmArmForDidNotPick() throws IOException {
        JsonObject c = fixture("tips");
        ProductInput wrong = ProductInput.newBuilder()
                .setBond(BondInput.newBuilder().setSecurity(security(c)).setCleanPrice(price(c).getPrice())).build();
        LocalTimestampProto asof = asof(c);
        PositionProto position = position(c);
        ModelValidationException e = assertThrows(ModelValidationException.class,
                () -> ValuationRequests.typed(asof, wrong, position, measures(c)));
        assertFalse(e instanceof MissingMarketDataError);
        assertEquals("product_input.bond", e.getField());
    }

    @Test
    void typedRejectsAnInputWithNoArm() throws IOException {
        JsonObject c = fixture("bond");
        LocalTimestampProto asof = asof(c);
        PositionProto position = position(c);
        ModelValidationException e = assertThrows(ModelValidationException.class,
                () -> ValuationRequests.typed(asof, ProductInput.getDefaultInstance(), position, measures(c)));
        assertEquals("product_input", e.getField());
    }

    @Test
    void errorsAreTypedInputErrors() throws IOException {
        JsonObject c = fixture("tips-missing-cpi");
        SecurityProto security = security(c);
        PriceProto price = price(c);
        RuntimeException raised = assertThrows(RuntimeException.class, () -> ProductInputs.forSecurity(security, price, MarketData.NONE));
        assertInstanceOf(ModelValidationException.class, raised);
        assertInstanceOf(IllegalArgumentException.class, new UnmappedProductTypeError("FX_SPOT", "UNKNOWN_COUPON_TYPE"));
    }
}
